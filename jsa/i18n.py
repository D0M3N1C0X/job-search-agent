def strings(lang: str = "en") -> dict[str, str]:
    """One language, with English filling any gap."""
    merged = dict(STRINGS["en"])
    merged.update({k: v for k, v in STRINGS.get(lang, {}).items() if v})
    return merged


def bundle() -> dict[str, dict[str, str]]:
    """Every language, each already backfilled — what the page embeds."""
    return {code: strings(code) for code in STRINGS}
